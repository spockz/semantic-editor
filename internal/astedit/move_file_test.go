func assertMoveFileRefusalUnchanged(t *testing.T, source, destination string, beforeSource, beforeDestination []byte, err error, substring, reason string) {
	t.Helper()
	if err == nil || !strings.Contains(err.Error(), substring) {
		t.Fatalf("MoveFile() error = %v, want %s", err, reason)
	}
	if string(beforeSource) != string(readMoveFileTestFile(t, source)) || string(beforeDestination) != string(readMoveFileTestFile(t, destination)) {
		t.Fatal("refused move changed source or destination")
	}
}

func readMoveFileTestFile(t *testing.T, path string) []byte {
	t.Helper()
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return content
}

