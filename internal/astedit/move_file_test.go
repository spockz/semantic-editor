func TestMoveFilePlansAgainstCurrentBufferOverlay(t *testing.T) {
	t.Parallel()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	writeMoveFixture(t, root, "go.mod", "module example.com/filemove\n\ngo 1.24\n")
	writeMoveFixture(t, root, "old/move.go", "package old\nfunc Move() {}\n")
	writeMoveFixture(t, root, "api/moved.go", "package api\n")
	source := filepath.Join(root, "old/move.go")
	destination := filepath.Join(root, "api/moved.go")
	beforeSource := readMoveFileTestFile(t, source)
	buffer, err := sourcebuf.New(t.Context(), root)
	if err != nil {
		t.Fatal(err)
	}
	ctx := sourcebuf.WithBuffer(t.Context(), buffer)
	if err := sourcebuf.Run(ctx, root, func(editCtx context.Context) error {
		if err := sourcebuf.WriteFile(editCtx, destination, []byte("package api\nfunc Move() {}\n")); err != nil {
			return err
		}
		if _, err := MoveFile(editCtx, source, destination, MoveFileOptions{}); err == nil {
			return fmt.Errorf("MoveFile() error = nil, want collision against current overlay")
		} else if !strings.Contains(err.Error(), `destination already declares "Move"`) {
			return fmt.Errorf("MoveFile() error = %w, want collision against current overlay", err)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	if err := buffer.Flush(t.Context()); err != nil {
		t.Fatal(err)
	}
	if string(readMoveFileTestFile(t, source)) != string(beforeSource) {
		t.Fatal("overlay collision changed the source file")
	}
	assertMoveFileContains(t, root, "api/moved.go", "func Move() {}")
}

