func TestMoveFileMovesClosedDeclarationsMatchingTestsAndTypedCallers(t *testing.T) {
	t.Parallel()
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	writeMoveFixture(t, root, "go.mod", "module example.com/filemove\n\ngo 1.24\n")
	writeMoveFixture(t, root, "old/foo.go", `// Copyright (c) Example.
package old
import "strings"
// This file-level note stays with the original package shell.

type Widget struct { value string }
func (w Widget) Value() string { return helper(w.value) }
func helper(value string) string { return strings.TrimSpace(value) }
func Build(value string) Widget { return Widget{value: helper(value)} }
const Version = 1
`)
	writeMoveFixture(t, root, "old/sibling.go", "package old\nimport \"strings\"\nfunc Remaining(value string) string { return strings.TrimSpace(value) }\n")
	writeMoveFixture(t, root, "old/foo_test.go", `// Test fixture license.
package old
import "testing"
func TestHelper(t *testing.T) { if helper(" x ") != "x" { t.Fatal("helper") } }
`)
	writeMoveFixture(t, root, "api/moved.go", "package api\n")
	writeMoveFixture(t, root, "api/sibling.go", "package api\nimport \"strings\"\nfunc Existing(value string) string { return strings.TrimSpace(value) }\n")
	writeMoveFixture(t, root, "client/client.go", `package client
import "example.com/filemove/old"
func Read() string { return old.Build(" x ").Value() }
func Method() func(old.Widget) string { return old.Widget.Value }
`)
	source := filepath.Join(root, "old/foo.go")
	destination := filepath.Join(root, "api/moved.go")
	if _, err := MoveFile(context.Background(), source, destination, MoveFileOptions{MoveMatchingTests: true}); err != nil {
		t.Fatalf("MoveFile() error = %v", err)
	}
	assertMoveFileContains(t, root, "old/foo.go", "// Copyright (c) Example.", "package old", "This file-level note stays with the original package shell.")
	assertMoveFileContains(t, root, "old/foo_test.go", "// Test fixture license.", "package old")
	assertMoveFileContains(t, root, "api/moved.go", "type Widget", "func (w Widget) Value()", "func helper", "func Build", "const Version", `"strings"`)
	assertMoveFileContains(t, root, "api/moved_test.go", "package api", "func TestHelper")
	assertMoveFileContains(t, root, "client/client.go", `"example.com/filemove/api"`, "api.Build")
	if _, err := os.Stat(filepath.Join(root, "old/foo_test.go")); err != nil {
		t.Fatalf("source test shell missing: %v", err)
	}
}

